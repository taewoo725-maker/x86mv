# X86MV V1.11.27: the 12x6 icons of the MV6 bottom bar (design D) -> bar6ic.inc.  Row r = two bytes (left 6 dots, right 6 dots), each in bits 7..2.
ICONS = {
 'ic6_prev':  ['##....#....#','##...##...##','##.####.####','##.####.####','##...##...##','##....#....#'],
 'ic6_next':  ['#....#....##','##...##...##','####.####.##','####.####.##','##...##...##','#....#....##'],
 'ic6_pause': ['..###..###..']*6,
 'ic6_play':  ['...#........','...###......','...######...','...######...','...###......','...#........'],
 'ic6_vol':   ['...#........','..##..#.....','####...#....','####...#....','..##..#.....','...#........'],
 'ic6_set':   ['...##.......','############','...##.......','........##..','############','........##..'],
}
out = ['; generated by mkbar6.py (design D, 12x6 icons): per row the left 6 dots, then the right 6 dots (bits 7..2)']
for name, rows in ICONS.items():
    assert len(rows) == 6 and all(len(r) == 12 for r in rows), name
    b = []
    for r in rows:
        for half in (r[:6], r[6:]):
            v = 0
            for i, ch in enumerate(half):
                if ch == '#': v |= 0x80 >> i
            b.append('0%02Xh' % v)
    out.append('%s: defb %s' % (name, ','.join(b)))
open('bar6ic.inc', 'w').write('\n'.join(out) + '\n')
